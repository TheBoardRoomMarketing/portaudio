    var prevList = sessionsIn(weeks[weeks.indexOf(weekKey) + 1] || "", "iso_week");
    var prev = aggregate(prevList);

    var byStrategy = {};
    list.forEach(function (s) {
      s.opportunities.forEach(function (o) {
        var k = o.strategy_id;
        byStrategy[k] = byStrategy[k] || { opps: 0, taken: 0, missed: 0, r: 0, mech: 0 };
        byStrategy[k].opps++;
        if (o.status === "TAKEN" || o.status === "BOT_EXECUTED") byStrategy[k].taken++;
        if (o.status === "MISSED") byStrategy[k].missed++;
        byStrategy[k].mech += o.mechanical_r || 0;
      });
      s.trades.forEach(function (t) {
        byStrategy[t.strategy_id] = byStrategy[t.strategy_id] || { opps: 0, taken: 0, missed: 0, r: 0, mech: 0 };
        byStrategy[t.strategy_id].r += t.r_multiple || 0;
      });
    });

    var mistakes = {};
    list.forEach(function (s) {
      s.trades.forEach(function (t) {
        t.tags.forEach(function (g) { mistakes[g] = (mistakes[g] || 0) + 1; });
      });
      if ((s.post || {}).missed_qualified) mistakes.MISSED_SETUP = (mistakes.MISSED_SETUP || 0) + 1;
    });
    var mistakeRows = Object.keys(mistakes).sort(function (x, y) { return mistakes[y] - mistakes[x]; })
      .map(function (k) { return { label: tagLabel(k), value: mistakes[k], display: String(mistakes[k]), warm: true }; });

    var best = list.slice().sort(function (x, y) { return (m(y).total_r || 0) - (m(x).total_r || 0); })[0];
    var worstProcess = list.slice().filter(function (s) { return m(s).self_reported_process_index != null; })
      .sort(function (x, y) { return (m(x).self_reported_process_index || 0) - (m(y).self_reported_process_index || 0); })[0];

    var focus = [];
    if (a.missed > 0) focus.push("Be at the desk for the " + (a.missed === 1 ? "one setup" : a.missed + " setups") +
      " that qualified while you were away — that is where most of the week's lost R sits.");
    if (mistakes.LATE_ENTRY) focus.push("Late entries appeared " + mistakes.LATE_ENTRY +
      " time" + (mistakes.LATE_ENTRY > 1 ? "s" : "") + ". Set the entry order at signal time rather than after confirming twice.");
    if (mistakes.OVERTRADE) focus.push("Overtrading was flagged on " + mistakes.OVERTRADE +
      " occasion" + (mistakes.OVERTRADE > 1 ? "s" : "") + ". Hold the planned trade cap.");
    if (!focus.length) focus.push("No repeat behaviour stands out this week. Keep the current pre-session routine.");

