  /* crosshair + tooltip for every chart that declares hot zones */
  function wireCharts() {
    [].forEach.call(document.querySelectorAll(".chart-wrap[data-chart]"), function (wrap) {
      var tip = wrap.querySelector(".tooltip");
      var svg = wrap.querySelector("svg");
      var cross = svg.querySelector(".cross");
      if (!tip || !svg) return;
      [].forEach.call(svg.querySelectorAll("[data-label]"), function (node) {
        node.addEventListener("mouseenter", function () {
          var box = svg.getBoundingClientRect();
          var vb = svg.viewBox.baseVal;
          var scale = box.width / vb.width;
          var cx = +node.getAttribute("data-cx") * scale;
          var cy = +node.getAttribute("data-cy") * scale;
          tip.textContent = node.getAttribute("data-label");
          tip.style.left = cx + "px";
          tip.style.top = (cy - 8) + "px";
          tip.classList.add("on");
          if (cross) {
            cross.setAttribute("x1", node.getAttribute("data-cx"));
            cross.setAttribute("x2", node.getAttribute("data-cx"));
            cross.setAttribute("opacity", "1");
          }
        });
      });
      wrap.addEventListener("mouseleave", function () {
        tip.classList.remove("on");
        if (cross) cross.setAttribute("opacity", "0");
      });
    });
  }

